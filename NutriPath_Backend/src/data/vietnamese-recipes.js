const ingredient = (value) => {
  const [name, amount, note] = value.split("|").map((part) => part.trim());
  return { name, amount, ...(note ? { note } : {}) };
};

function createRecipe(spec, index) {
  const number = String(index + 1).padStart(3, "0");
  const [name, category, timeMinutes, calories, macros, ingredientText, prep, cook, finish] = spec;
  const [protein, carbs, fat, fiber] = macros;
  const tags = ["Healthy thuần Việt", category];
  if (protein >= 25) tags.push("Giàu đạm");
  if (category === "Món chay") tags.push("Món chay");
  if (calories <= 300) tags.push("Dưới 300 kcal", "Low-cal");

  return {
    id: `recipe-vn-${number}`,
    name,
    image: `/images/recipes/vietnamese/recipe-vn-${number}.webp`,
    imagePrompt: `Ảnh món ${name}, món ăn Việt Nam healthy, trình bày đúng nguyên liệu, ảnh chụp món ăn chân thực`,
    timeMinutes,
    calories,
    difficulty: timeMinutes <= 25 ? 1 : timeMinutes <= 50 ? 2 : 3,
    tags,
    servings: 1,
    ingredients: ingredientText.split(";").map(ingredient),
    steps: [
      `Chuẩn bị nguyên liệu (3-5 phút): Cân đủ nguyên liệu cho 1 khẩu phần theo danh sách. Rau, thịt và hải sản phải còn tươi; rửa riêng từng nhóm để tránh nhiễm chéo.`,
      `Sơ chế: ${prep}`,
      `Nấu chính: ${cook}`,
      `Hoàn thiện: ${finish}`,
      `Kiểm tra và dùng món: Chia đúng 1 khẩu phần, dùng khi còn ấm. Thành phẩm cần giữ được màu tự nhiên, không đọng nhiều dầu và có vị vừa; thông tin dinh dưỡng là mức ước tính, có thể dao động theo nguyên liệu thực tế.`,
    ],
    nutrition: { protein, carbs, fat, fiber },
    nutritionBasis: "Ước tính cho 1 khẩu phần theo đúng định lượng nguyên liệu.",
    healthNotes: [
      "Ưu tiên gia vị vừa phải và không tự ý tăng lượng dầu, đường hoặc nước chấm.",
      "Người có bệnh nền hoặc dị ứng thực phẩm cần điều chỉnh nguyên liệu theo hướng dẫn của chuyên gia.",
    ],
    cuisine: "Việt Nam",
    isCurated: true,
  };
}

